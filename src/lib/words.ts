export const ALFABETO = [
  "A", "B", "C", "D", "E", "F", "G", "H", "I", "J", "K", "L", "M",
  "N", "Ñ", "O", "P", "Q", "R", "S", "T", "U", "V", "W", "X", "Y", "Z",
];

// Quita los acentos de las vocales para facilitar las coincidencias, pero
// CONSERVA la Ñ (no la convierte en N). Así, al pulsar "A" se revela una "Á",
// y la "Ñ" sigue siendo una letra aparte que requiere su propia tecla.
export function normalizar(texto: string): string {
  return texto
    .toUpperCase()
    .replace(/[ÁÀÄ]/g, "A")
    .replace(/[ÉÈË]/g, "E")
    .replace(/[ÍÌÏ]/g, "I")
    .replace(/[ÓÒÖ]/g, "O")
    .replace(/[ÚÙÜ]/g, "U");
}
